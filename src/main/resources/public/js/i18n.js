let currentLang = localStorage.getItem('craftpanel_lang') || 'en';

export const i18n = {
  getLanguage() {
    return currentLang;
  },

  setLanguage(lang) {
    if (translations[lang]) {
      currentLang = lang;
      localStorage.setItem('craftpanel_lang', lang);
      window.dispatchEvent(new CustomEvent('language:changed', { detail: lang }));
    }
  },

  t(key, fallback = '', params = null) {
    if (typeof fallback === 'object' && fallback !== null) {
      params = fallback;
      fallback = '';
    }
    const dict = translations[currentLang] || translations.en;
    let str = (dict && dict[key]) ? dict[key] : ((translations.en && translations.en[key]) ? translations.en[key] : (fallback || key));
    if (params && typeof params === 'object') {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
      }
    }
    return str;
  }
};
